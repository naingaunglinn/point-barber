// Builds the vendored copy of Google's myanmar-tools JavaScript client (Zawgyi detector and converter,
// Apache-2.0) into src/text/myanmar-tools/ — add-shared-ui-components task 2.11 · AD-FORM-13.
//
//   node packages/shared/scripts/vendor-myanmar-tools.mjs <myanmar-tools-1.2.0.tgz>
//
// Why vendored, not an npm dependency (owner decision of 12/Oct/2026): the npm release 1.2.0 ships
// without its build output and does not load; 1.1.3 is a Node-only build that fails in a browser
// (`new Buffer`), and the client has had no release since 2020. 1.2.0 carries the retrained
// multi-language model. This script does what the package's own gulp build does — inline the
// model and the transliteration rules, resolve the `// @if NODEJS` blocks — with one change: the
// model is decoded with `atob`, which Node 24 and every browser have, so the same file runs in the
// API and in the web app.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// npm `dist.integrity` of myanmar-tools@1.2.0 (= github.com/google/myanmar-tools clients/js at
// 2b171c6, "Node.js version 1.2.0").
const INTEGRITY =
  'sha512-cfrw2b1QsEW6C4hU3SI79wSCeCREYgh2XZOcu4TWOu2CPbHaxAyRT9eiOehKTY/wUbrgkkYZkxZj9C5gDEP1xw==';

const tarball = process.argv[2];
if (tarball === undefined) {
  console.error('usage: vendor-myanmar-tools.mjs <myanmar-tools-1.2.0.tgz>');
  process.exit(1);
}
const integrity = `sha512-${createHash('sha512').update(readFileSync(tarball)).digest('base64')}`;
if (integrity !== INTEGRITY) {
  console.error(`vendor-myanmar-tools: ${tarball} is not myanmar-tools 1.2.0 (${integrity})`);
  process.exit(1);
}

const work = mkdtempSync(join(tmpdir(), 'myanmar-tools-'));
execFileSync('tar', ['-xzf', tarball, '-C', work]);
const pkg = join(work, 'package');
const read = (path) => readFileSync(join(pkg, path), 'utf8');

/** The package's gulp substitutions: model and rules inlined (a function, so `$'` in a rule stays). */
function inline(source) {
  const model = readFileSync(join(pkg, 'resources/zawgyiUnicodeModel.dat'), 'base64');
  const rules = (name) => `declare function getAllRules${name}(): TranslitRule[][]; // PLACEHOLDER`;
  return source
    .replace('<BASE64_DATA_PLACEHOLDER>', () => model)
    .replace(rules('Z2U'), () => read('resources/Z2U.js'))
    .replace(rules('U2Z'), () => read('resources/U2Z.js'))
    .replace(rules('ZNorm'), () => read('resources/ZNorm.js'));
}

/** `// @if NODEJS` blocks kept, `// @if !NODEJS` blocks dropped (gulp-preprocess with NODEJS). */
function preprocess(source) {
  return source.replace(
    /^[ \t]*\/\/ @if (!?)NODEJS\n([\s\S]*?)^[ \t]*\/\/ @endif\n/gm,
    (_block, not, body) => (not === '!' ? '' : body),
  );
}

const NODE_DECODE =
  /getArrayBuffer = \(\) => \{\n\s*\/\/ Buffer is defined on Node\n[\s\S]*?\n\};\n/;
const ATOB_DECODE = `getArrayBuffer = () => {
    // The browser decoding of the package, also available in Node 24 (vendor change, see header).
    const binaryString = atob(DATA);
    const arrayBuffer = new ArrayBuffer(binaryString.length);
    const u8view = new Uint8Array(arrayBuffer);
    for (let i = 0; i < binaryString.length; i++) {
        u8view[i] = binaryString.charCodeAt(i);
    }
    return arrayBuffer;
};
`;

const HEADER = `// @ts-nocheck — third-party code, kept as generated (see below); the wrapper text/zawgyi.ts is typed.
/* Vendored from myanmar-tools 1.2.0 (npm ${INTEGRITY}),
 * github.com/google/myanmar-tools clients/js — Copyright 2017 Google LLC, Apache License 2.0
 * (LICENSE.md in this folder). Generated by packages/shared/scripts/vendor-myanmar-tools.mjs: the
 * model and the rules are inlined as the package's own build does, and the model is decoded with
 * \`atob\` instead of Node's \`Buffer\`. Do not edit by hand — change the script and run it again. */
`;

const out = resolve(dirname(fileURLToPath(import.meta.url)), '../src/text/myanmar-tools');
mkdirSync(out, { recursive: true });

const detector = preprocess(inline(read('src/zawgyi_detector.ts')));
if (!NODE_DECODE.test(detector)) {
  console.error('vendor-myanmar-tools: the Node decoding block was not found — check the source');
  process.exit(1);
}
writeFileSync(
  join(out, 'zawgyi-detector.ts'),
  HEADER + detector.replace(NODE_DECODE, () => ATOB_DECODE),
);
writeFileSync(
  join(out, 'zawgyi-converter.ts'),
  HEADER + preprocess(inline(read('src/zawgyi_converter.ts'))),
);
copyFileSync(join(pkg, 'LICENSE.md'), join(out, 'LICENSE.md'));
rmSync(work, { recursive: true, force: true });
console.log(`vendor-myanmar-tools: wrote ${out}`);
